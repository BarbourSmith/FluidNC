//This function saves the current z-axis position to the non-volitle storage
void Maslow_::saveZPos() {
    nvs_handle_t nvsHandle;
    esp_err_t    ret = nvs_open("maslow", NVS_READWRITE, &nvsHandle);
    if (ret != ESP_OK) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " opening NVS handle!\n");
        return;
    }

    // Read the current value
    int32_t currentZPos;
    ret = nvs_get_i32(nvsHandle, "zPos", &currentZPos);
    if (ret != ESP_OK && ret != ESP_ERR_NVS_NOT_FOUND) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " reading from NVS!\n");
        return;
    }

    // Write - Convert the float to an int32_t and write only if it has changed
    union FloatInt32 {
        float   f;
        int32_t i;
    };
    FloatInt32 fi;
    fi.f = targetZ;
    if (ret == ESP_ERR_NVS_NOT_FOUND || currentZPos != fi.i) {  // Only write if the value has changed
        ret = nvs_set_i32(nvsHandle, "zPos", fi.i);
        if (ret != ESP_OK) {
            log_info("Error " + std::string(esp_err_to_name(ret)) + " writing to NVS!\n");
        } else {
            //log_info("Written value = " + std::to_string(targetZ));

            // Commit written value to non-volatile storage
            ret = nvs_commit(nvsHandle);
            if (ret != ESP_OK) {
                log_info("Error " + std::string(esp_err_to_name(ret)) + " committing changes to NVS!\n");
            }
        }
    }
}

//This function loads the z-axis position from the non-volitle storage
float Maslow_::currentZHome() const {
    float zHome = gc_state.coord_system[Z_AXIS] + gc_state.coord_offset[Z_AXIS];
    if (Z_AXIS == TOOL_LENGTH_OFFSET_AXIS) {
        zHome += gc_state.tool_length_offset;
    }
    return zHome;
}

void Maslow_::loadZPos() {
    static constexpr float MIN_VALID_Z_MM = 0.0f;
    static constexpr float MAX_VALID_Z_MM = 72.0f;

    nvs_handle_t nvsHandle;
    esp_err_t    ret = nvs_open("maslow", NVS_READWRITE, &nvsHandle);
    if (ret != ESP_OK) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " opening NVS handle!\n");
        return;
    }

    // Read
    int32_t value2;
    ret = nvs_get_i32(nvsHandle, "zPos", &value2);
    if (ret != ESP_OK) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " reading from NVS!");
    } else {
        union FloatInt32 {
            float   f;
            int32_t i;
        };
        FloatInt32 fi;
        fi.i    = value2;
        targetZ = fi.f;

        // gc_state is zero-initialized before gc_init() runs, so if coordinate
        // offsets are not loaded yet, Z home safely defaults to 0 here.
        float zHome = currentZHome();

        float zPosition = targetZ - zHome;
        bool zPositionOutOfRange = !std::isfinite(targetZ) || targetZ < MIN_VALID_Z_MM || targetZ > MAX_VALID_Z_MM;
        bool zHomeOutOfRange = !std::isfinite(zHome) || zHome < MIN_VALID_Z_MM || zHome > MAX_VALID_Z_MM;

        if (zPositionOutOfRange) {
            log_warn("Maslow Z position warning: Z position out of range, check Z home is valid (Z home=" << zHome << "mm, Z position=" << zPosition
                                                                                                           << "mm, Z home + Z position=" << targetZ
                                                                                                           << "mm). Valid range is 0 to 72mm inclusive. Power cycling Maslow may clear error.");
        }

        if (zHomeOutOfRange) {
            log_warn("Maslow Z home reset warning: Startup Z home is out of range (Zm=" << targetZ << "mm, Z home=" << zHome
                                                                                          << "mm). Valid range for Z home is 0 to 72mm inclusive. Resetting Z home to Zm.");
        }

        // Use Z_AXIS constant (2) for cartesian coordinate, not motor index (4)
        float* mpos  = get_mpos();
        mpos[Z_AXIS] = targetZ;
        set_motor_steps_from_mpos(mpos);

        log_info("Current z-axis position loaded as: " << targetZ);

        gc_sync_position();  //This updates the Gcode engine with the new position from the stepping engine that we set with set_motor_steps
        plan_sync_position();

        if (zHomeOutOfRange) {
            // Reset Z home to Zm by clearing any transient G92 offset and then setting the
            // work coordinate system so that work Z = 0 at the current machine position (Zm).
            char  clear_offset_line[] = "G92.1";
            Error result              = gc_execute_line(clear_offset_line);
            if (result != Error::Ok) {
                log_error("Failed to clear transient Z home offset: " << errorString(result));
            } else {
                char set_home_line[] = "G10 L20 P0 Z0";
                result               = gc_execute_line(set_home_line);
                if (result != Error::Ok) {
                    log_error("Failed to set work coordinate Z home to Zm: " << errorString(result));
                }
            }
        }
    }
}

void Maslow_::logLoadZPosDebug() {
    float zHome = currentZHome();
    float zPosition = targetZ - zHome;
    log_info("Zm=" << targetZ << "mm, Z home=" << zHome << "mm, Z position=" << zPosition << "mm");
}

/** Sets the 'bottom' Z position, this is a 'stop' beyond which travel cannot continue */
void Maslow_::setZStop() {
    targetZ = 0;

    // Use Z_AXIS constant (2) for cartesian coordinate, not motor index (4)
    float* mpos  = get_mpos();
    mpos[Z_AXIS] = targetZ;
    set_motor_steps_from_mpos(mpos);

    gc_sync_position();  //This updates the Gcode engine with the new position from the stepping engine that we set with set_motor_steps
    plan_sync_position();

    // Persist Z home at 0 by clearing transient G92 offset and updating the
    // active work coordinate system at the current machine position.
    char  clear_offset_line[] = "G92.1";
    Error result              = gc_execute_line(clear_offset_line);
    if (result != Error::Ok) {
        log_error("Failed to clear transient Z home offset: " << errorString(result));
        return;
    }

    char set_home_line[] = "G10 L20 P0 Z0";
    result               = gc_execute_line(set_home_line);
    if (result != Error::Ok) {
        log_error("Failed to set persistent Z home: " << errorString(result));
    }
}

//This function saves the current belt positions to non-volatile storage
void Maslow_::saveBeltPositions() {
    // Only save if in a valid state (belts are tight and at known positions)
    int currentState = calibration.getCurrentState();
    if (currentState != READY_TO_CUT && currentState != RETRACTED && currentState != EXTENDEDOUT) {
        log_debug("Belt positions NOT saved - invalid state (not READY_TO_CUT, RETRACTED, or EXTENDEDOUT), currentState=" << currentState);
        return;
    }

    nvs_handle_t nvsHandle;
    esp_err_t    ret = nvs_open("maslow", NVS_READWRITE, &nvsHandle);
    if (ret != ESP_OK) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " opening NVS handle for belt positions!\n");
        return;
    }

    // Union for float to int32_t conversion
    union FloatInt32 {
        float   f;
        int32_t i;
    };

    // Get current belt positions
    float tlPos = axis[_TL].getPosition();
    float trPos = axis[_TR].getPosition();
    float blPos = axis[_BL].getPosition();
    float brPos = axis[_BR].getPosition();

    // Get current raw encoder angles for validation on restore
    uint16_t tlAngle = axis[_TL].getRawEncoderAngle();
    uint16_t trAngle = axis[_TR].getRawEncoderAngle();
    uint16_t blAngle = axis[_BL].getRawEncoderAngle();
    uint16_t brAngle = axis[_BR].getRawEncoderAngle();

    // Save TL belt position
    int32_t currentTLPos;
    ret = nvs_get_i32(nvsHandle, "tlPos", &currentTLPos);
    FloatInt32 tlFi;
    tlFi.f = tlPos;
    if (ret == ESP_ERR_NVS_NOT_FOUND || currentTLPos != tlFi.i) {
        ret = nvs_set_i32(nvsHandle, "tlPos", tlFi.i);
        if (ret != ESP_OK) {
            log_info("Error " + std::string(esp_err_to_name(ret)) + " writing TL belt position to NVS!\n");
        }
    }
    // Save TL raw encoder angle
    nvs_set_i32(nvsHandle, "tlAngle", tlAngle);

    // Save TR belt position
    int32_t currentTRPos;
    ret = nvs_get_i32(nvsHandle, "trPos", &currentTRPos);
    FloatInt32 trFi;
    trFi.f = trPos;
    if (ret == ESP_ERR_NVS_NOT_FOUND || currentTRPos != trFi.i) {
        ret = nvs_set_i32(nvsHandle, "trPos", trFi.i);
        if (ret != ESP_OK) {
            log_info("Error " + std::string(esp_err_to_name(ret)) + " writing TR belt position to NVS!\n");
        }
    }
    // Save TR raw encoder angle
    nvs_set_i32(nvsHandle, "trAngle", trAngle);

    // Save BL belt position
    int32_t currentBLPos;
    ret = nvs_get_i32(nvsHandle, "blPos", &currentBLPos);
    FloatInt32 blFi;
    blFi.f = blPos;
    if (ret == ESP_ERR_NVS_NOT_FOUND || currentBLPos != blFi.i) {
        ret = nvs_set_i32(nvsHandle, "blPos", blFi.i);
        if (ret != ESP_OK) {
            log_info("Error " + std::string(esp_err_to_name(ret)) + " writing BL belt position to NVS!\n");
        }
    }
    // Save BL raw encoder angle
    nvs_set_i32(nvsHandle, "blAngle", blAngle);

    // Save BR belt position
    int32_t currentBRPos;
    ret = nvs_get_i32(nvsHandle, "brPos", &currentBRPos);
    FloatInt32 brFi;
    brFi.f = brPos;
    if (ret == ESP_ERR_NVS_NOT_FOUND || currentBRPos != brFi.i) {
        ret = nvs_set_i32(nvsHandle, "brPos", brFi.i);
        if (ret != ESP_OK) {
            log_info("Error " + std::string(esp_err_to_name(ret)) + " writing BR belt position to NVS!\n");
        }
    }
    // Save BR raw encoder angle
    nvs_set_i32(nvsHandle, "brAngle", brAngle);

    // Mark the data as valid
    ret = nvs_set_i32(nvsHandle, "beltValid", 1);
    if (ret != ESP_OK) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " writing belt validity marker to NVS!\n");
    }

    // Commit all changes to non-volatile storage
    ret = nvs_commit(nvsHandle);
    if (ret != ESP_OK) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " committing belt position changes to NVS!\n");
    }

    nvs_close(nvsHandle);

    // Log the save operation
    char* buffer = getLogBuffer();
    snprintf(buffer, 1400, "Belt positions saved to NVS: TL=%g TR=%g BL=%g BR=%g state=%d", tlPos, trPos, blPos, brPos, currentState);
    log_debug(buffer);
    releaseLogBuffer();
}

//This function loads the belt positions from non-volatile storage
void Maslow_::loadBeltPositions() {
    nvs_handle_t nvsHandle;
    esp_err_t    ret = nvs_open("maslow", NVS_READWRITE, &nvsHandle);
    if (ret != ESP_OK) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " opening NVS handle for belt positions!\n");
        return;
    }

    // Check if the data is valid
    int32_t validityMarker;
    ret = nvs_get_i32(nvsHandle, "beltValid", &validityMarker);
    if (ret != ESP_OK || validityMarker != 1) {
        log_debug("Belt positions NOT loaded from NVS - data is stale/invalid or not found");
        if (ret == ESP_ERR_NVS_NOT_FOUND) {
            log_info("No saved belt positions found in NVS - machine will remain in UNKNOWN state until belts are calibrated/extended");
        } else if (validityMarker != 1) {
            log_info("Saved belt positions in NVS are marked as stale/invalid (value="
                     << validityMarker << ") - machine will remain in UNKNOWN state until belts are calibrated/extended");
        }
        nvs_close(nvsHandle);
        return;
    }

    // Union for int32_t to float conversion
    union FloatInt32 {
        float   f;
        int32_t i;
    };

    // Load TL belt position
    int32_t tlValue;
    ret         = nvs_get_i32(nvsHandle, "tlPos", &tlValue);
    float tlPos = 0;
    if (ret == ESP_OK) {
        FloatInt32 tlFi;
        tlFi.i = tlValue;
        tlPos  = tlFi.f;

        // Load saved encoder angle and compare with current
        int32_t savedTLAngle;
        ret = nvs_get_i32(nvsHandle, "tlAngle", &savedTLAngle);
        if (ret == ESP_OK) {
            uint16_t currentTLAngle = axis[_TL].getRawEncoderAngle();
            int32_t  angleDiff      = currentTLAngle - savedTLAngle;

            // Handle wrap-around: if difference is > 2048, it wrapped the other direction
            if (angleDiff > 2048)
                angleDiff -= 4096;
            if (angleDiff < -2048)
                angleDiff += 4096;

            // If angle difference is within 1/4 turn (1024 counts), adjust belt position for small movement
            if (abs(angleDiff) < 1024) {
                float movementMM = (angleDiff / 4096.0f) * axis[_TL].getMmPerRevolution() * -1.0f;
                tlPos += movementMM;
            } else {
                log_info("TL encoder angle difference too large (" << angleDiff << " counts), treating belt positions as stale");
                nvs_close(nvsHandle);
                return;
            }
        }

        // Set motor steps directly for TL belt (A axis = motor 0)
        set_motor_steps(0, mpos_to_steps(tlPos, 0));
        axis[_TL].setTarget(tlPos);
        // Initialize encoder cumulative position to match adjusted belt length
        axis[_TL].setPosition(tlPos);
    } else if (ret != ESP_ERR_NVS_NOT_FOUND) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " reading TL belt position from NVS!");
    }

    // Load TR belt position
    int32_t trValue;
    ret         = nvs_get_i32(nvsHandle, "trPos", &trValue);
    float trPos = 0;
    if (ret == ESP_OK) {
        FloatInt32 trFi;
        trFi.i = trValue;
        trPos  = trFi.f;

        // Load saved encoder angle and compare with current
        int32_t savedTRAngle;
        ret = nvs_get_i32(nvsHandle, "trAngle", &savedTRAngle);
        if (ret == ESP_OK) {
            uint16_t currentTRAngle = axis[_TR].getRawEncoderAngle();
            int32_t  angleDiff      = currentTRAngle - savedTRAngle;

            // Handle wrap-around
            if (angleDiff > 2048)
                angleDiff -= 4096;
            if (angleDiff < -2048)
                angleDiff += 4096;

            if (abs(angleDiff) < 1024) {
                float movementMM = (angleDiff / 4096.0f) * axis[_TR].getMmPerRevolution() * -1.0f;
                trPos += movementMM;
            } else {
                log_info("TR encoder angle difference too large (" << angleDiff << " counts), treating belt positions as stale");
                nvs_close(nvsHandle);
                return;
            }
        }

        // Set motor steps directly for TR belt (B axis = motor 1)
        set_motor_steps(1, mpos_to_steps(trPos, 1));
        axis[_TR].setTarget(trPos);
        axis[_TR].setPosition(trPos);
    } else if (ret != ESP_ERR_NVS_NOT_FOUND) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " reading TR belt position from NVS!");
    }

    // Load BL belt position
    int32_t blValue;
    ret         = nvs_get_i32(nvsHandle, "blPos", &blValue);
    float blPos = 0;
    if (ret == ESP_OK) {
        FloatInt32 blFi;
        blFi.i = blValue;
        blPos  = blFi.f;

        // Load saved encoder angle and compare with current
        int32_t savedBLAngle;
        ret = nvs_get_i32(nvsHandle, "blAngle", &savedBLAngle);
        if (ret == ESP_OK) {
            uint16_t currentBLAngle = axis[_BL].getRawEncoderAngle();
            int32_t  angleDiff      = currentBLAngle - savedBLAngle;

            // Handle wrap-around
            if (angleDiff > 2048)
                angleDiff -= 4096;
            if (angleDiff < -2048)
                angleDiff += 4096;

            if (abs(angleDiff) < 1024) {
                float movementMM = (angleDiff / 4096.0f) * axis[_BL].getMmPerRevolution() * -1.0f;
                blPos += movementMM;
            } else {
                log_info("BL encoder angle difference too large (" << angleDiff << " counts), treating belt positions as stale");
                nvs_close(nvsHandle);
                return;
            }
        }

        // Set motor steps directly for BL belt (C axis = motor 2)
        set_motor_steps(2, mpos_to_steps(blPos, 2));
        axis[_BL].setTarget(blPos);
        axis[_BL].setPosition(blPos);
    } else if (ret != ESP_ERR_NVS_NOT_FOUND) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " reading BL belt position from NVS!");
    }

    // Load BR belt position
    int32_t brValue;
    ret         = nvs_get_i32(nvsHandle, "brPos", &brValue);
    float brPos = 0;
    if (ret == ESP_OK) {
        FloatInt32 brFi;
        brFi.i = brValue;
        brPos  = brFi.f;

        // Load saved encoder angle and compare with current
        int32_t savedBRAngle;
        ret = nvs_get_i32(nvsHandle, "brAngle", &savedBRAngle);
        if (ret == ESP_OK) {
            uint16_t currentBRAngle = axis[_BR].getRawEncoderAngle();
            int32_t  angleDiff      = currentBRAngle - savedBRAngle;

            // Handle wrap-around
            if (angleDiff > 2048)
                angleDiff -= 4096;
            if (angleDiff < -2048)
                angleDiff += 4096;

            if (abs(angleDiff) < 1024) {
                float movementMM = (angleDiff / 4096.0f) * axis[_BR].getMmPerRevolution() * -1.0f;
                brPos += movementMM;
            } else {
                log_info("BR encoder angle difference too large (" << angleDiff << " counts), treating belt positions as stale");
                nvs_close(nvsHandle);
                return;
            }
        }

        // Set motor steps directly for BR belt (D axis = motor 3)
        set_motor_steps(3, mpos_to_steps(brPos, 3));
        axis[_BR].setTarget(brPos);
        axis[_BR].setPosition(brPos);
    } else if (ret != ESP_ERR_NVS_NOT_FOUND) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " reading BR belt position from NVS!");
    }

    nvs_close(nvsHandle);

    // Sync position with G-code parser and planner
    gc_sync_position();
    plan_sync_position();

    // Determine the state based on belt lengths
    // If all belt lengths are near zero (within threshold), go to RETRACTED state, otherwise EXTENDEDOUT
    // Loading into EXTENDEDOUT requires the user to press "Apply Tension" to enter READY_TO_CUT state,
    // which allows the machine to measure its frame and verify everything is as expected
    // Use threshold of 0.5mm to account for encoder drift and small movements during save/restore
    const float retractedThreshold = 0.5;  // mm
    bool        allNearZero = (fabs(tlPos) < retractedThreshold && fabs(trPos) < retractedThreshold && fabs(blPos) < retractedThreshold &&
                        fabs(brPos) < retractedThreshold);
    int         newState    = allNearZero ? RETRACTED : EXTENDEDOUT;

    // Set the state directly (bypass requestStateChange validation)
    // This is appropriate when restoring a known-good saved state at boot time
    // requestStateChange() would reject EXTENDEDOUT from UNKNOWN state
    calibration.currentState = newState;

    // Set the extended* state variables in the Calibration class to match the restored state
    // When belts are extended (EXTENDEDOUT), mark all belts as extended
    // When belts are retracted (RETRACTED), mark all belts as not extended
    if (newState == EXTENDEDOUT) {
        calibration.setExtendedState(true, true, true, true);
        log_debug("Set Find Anchors extended* variables to true (belts are extended)");
    } else {
        calibration.setExtendedState(false, false, false, false);
        log_debug("Set Find Anchors extended* variables to false (belts are retracted)");
    }

    // Disable alarm if present
    if (sys.state() == State::Alarm) {
        sys.set_state(State::Idle);
    }
    char* buffer2 = getLogBuffer();
    snprintf(
        buffer2, 1400, "Belt positions after encoder adjustment: TL=%g TR=%g BL=%g BR=%g newState=%d", tlPos, trPos, blPos, brPos, newState);
    log_debug(buffer2);
    releaseLogBuffer();
}

//This function marks the belt positions in NVS as stale/invalid
void Maslow_::markBeltPositionsStale() {
    nvs_handle_t nvsHandle;
    esp_err_t    ret = nvs_open("maslow", NVS_READWRITE, &nvsHandle);
    if (ret != ESP_OK) {
        log_info("Error " + std::string(esp_err_to_name(ret)) + " opening NVS handle for belt positions!\n");
        return;
    }

    // Read the current validity marker value
    int32_t currentValid;
    ret = nvs_get_i32(nvsHandle, "beltValid", &currentValid);

    // Only write if the value needs to change (not already 0)
    // This preserves NVS write cycles since NVS has a finite write limit
    if (ret == ESP_ERR_NVS_NOT_FOUND || currentValid != 0) {
        // Mark the data as invalid by setting validity marker to 0
        ret = nvs_set_i32(nvsHandle, "beltValid", 0);
        if (ret != ESP_OK) {
            log_info("Error " + std::string(esp_err_to_name(ret)) + " writing belt validity marker to NVS!\n");
        } else {
            // Commit the change
            ret = nvs_commit(nvsHandle);
            if (ret != ESP_OK) {
                log_info("Error " + std::string(esp_err_to_name(ret)) + " committing belt validity change to NVS!\n");
            }
        }
    }

    nvs_close(nvsHandle);

    int currentState = calibration.getCurrentState();
    log_debug("Belt positions marked as stale/invalid in NVS, state=" << currentState);
}


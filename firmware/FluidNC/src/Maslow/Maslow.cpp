// Initialization function
void Maslow_::begin(void (*sys_rt)()) {
    Wire.begin(5, 4, 200000);
    I2CMux.begin(TCAADDR, Wire);

    axis[_TL].begin(tlIn1Pin, tlIn2Pin, tlADCPin, TLEncoderLine, tlIn1Channel, tlIn2Channel);
    axis[_TR].begin(trIn1Pin, trIn2Pin, trADCPin, TREncoderLine, trIn1Channel, trIn2Channel);
    axis[_BL].begin(blIn1Pin, blIn2Pin, blADCPin, BLEncoderLine, blIn1Channel, blIn2Channel);
    axis[_BR].begin(brIn1Pin, brIn2Pin, brADCPin, BREncoderLine, brIn1Channel, brIn2Channel);

    calibration.axisHomed[_BL] = false;
    calibration.axisHomed[_BR] = false;
    calibration.axisHomed[_TR] = false;
    calibration.axisHomed[_TL] = false;

    //Recompute the center XY
    calibration.updateCenterXY();

    pinMode(coolingFanPin, OUTPUT);
    pinMode(ETHERNETLEDPIN, OUTPUT);
    pinMode(WIFILED, OUTPUT);
    pinMode(REDLED, OUTPUT);

    digitalWrite(ETHERNETLEDPIN, LOW);
    digitalWrite(REDLED, LOW);

    pinMode(SERVOFAULT, INPUT);

    lastCallToUpdate = millis();

    // Only load positions from NVS on the first call to begin() (initial power-on)
    // Subsequent calls (e.g., after soft reset) should not reload stale NVS data
    static bool positionsLoaded = false;
    if (!positionsLoaded) {
        loadZPos();           //Loads the z-axis position from EEPROM
        loadBeltPositions();  //Loads the belt positions from EEPROM
        positionsLoaded = true;
    }

    stopMotors();

    Wire.setTimeOut(10);

    if (error) {
        log_error(M + " failed to initialize - fix errors and restart");
    } else {
        log_info("Starting " + M + " Version " << VERSION_NUMBER);
        log_info("Maslow_Retract_Current_Threshold: " << calibration.retractCurrentThreshold);
    }
}

// Maslow main loop, everything is processed here
void Maslow_::update() {
    // Register with hardware watchdog on first call and feed it every call.
    // If update() stops being called entirely (Core 1 frozen), the hardware
    // watchdog will reset the device, stopping all PWM outputs.
    static bool wdt_registered = false;
    if (!wdt_registered) {
        if (esp_task_wdt_add(NULL) == ESP_OK) {
            log_info("Maslow update loop registered with hardware watchdog");
        } else {
            log_warn("Could not register Maslow update loop with hardware watchdog");
        }
        wdt_registered = true;
    }
    esp_task_wdt_reset();

    static State prevState = sys.state();

    // Watchdog fired: rapid double-blink on both RED and WiFi LEDs (distinct from the slow
    // 300 ms error blink).  Triggered when update() is not called for > UPDATE_WATCHDOG_MS.
    // Pattern: 100 ms ON, 100 ms OFF, 100 ms ON, 800 ms pause (repeating).
    // Both LEDs flash together so the pattern is visible from any angle.
    // Recovery: power-cycle the machine.
    if (watchdogFired) {
        stopMotors();
        static unsigned long wdTimer  = millis();
        static int           wdPhase  = 0;  // 0=on1, 1=off1, 2=on2, 3=pause
        static const int     wdMS[]   = { 100, 100, 100, 800 };
        if (millis() - wdTimer >= (unsigned long)wdMS[wdPhase]) {
            wdPhase = (wdPhase + 1) % 4;
            bool ledsOn = (wdPhase == 0 || wdPhase == 2);
            digitalWrite(REDLED, ledsOn ? HIGH : LOW);
            digitalWrite(WIFILED, ledsOn ? HIGH : LOW);
            wdTimer = millis();
        }
        return;
    }

    // Error / emergency-stop state: slow 300 ms single-blink on the RED LED only.
    // Triggered by eStop() (position error > 15 mm while running, $ESTOP command) or by
    // a hardware fault detected at startup (encoder or motor not found).
    // The machine ignores all movement commands while in this state.
    // Recovery: fix the underlying cause (check console log for details), then power-cycle.
    if (error) {
        static unsigned long timer = millis();
        static bool          st    = true;  //This is used to blink the LED
        if (millis() - timer > 300) {
            stopMotors();
            st = !st;
            digitalWrite(REDLED, st);
            timer = millis();
            if (errorMessage != "") {
                log_error(errorMessage.c_str());
            }
            errorMessage = "";
        }
        return;
    }

    //Blinks the Ethernet LEDs randomly...these have been removed from the board, this pin should be freed up
    if (random(10000) == 0) {
        digitalWrite(ETHERNETLEDPIN, LOW);
    }
    if (random(10000) == 0) {
        digitalWrite(ETHERNETLEDPIN, HIGH);
    }

    //Save the z-axis position if the prevous state was jog or cycle and the current state is idle
    if ((prevState == State::Jog || prevState == State::Cycle) && sys.state() == State::Idle) {
        saveZPos();
        // Only save belt positions when in READY_TO_CUT, RETRACTED, or EXTENDEDOUT state (belts are tight and valid)
        int currentMaslowState = calibration.getCurrentState();
        if (currentMaslowState == READY_TO_CUT || currentMaslowState == RETRACTED || currentMaslowState == EXTENDEDOUT) {
            saveBeltPositions();
        }
    }

    // Track state changes and mark belt positions as stale when leaving valid states
    static int prevMaslowState    = calibration.getCurrentState();
    int        currentMaslowState = calibration.getCurrentState();
    if (prevMaslowState != currentMaslowState) {
        // If we're leaving READY_TO_CUT, RETRACTED, or EXTENDEDOUT, mark positions as stale
        if ((prevMaslowState == READY_TO_CUT || prevMaslowState == RETRACTED || prevMaslowState == EXTENDEDOUT) &&
            (currentMaslowState != READY_TO_CUT && currentMaslowState != RETRACTED && currentMaslowState != EXTENDEDOUT)) {
            markBeltPositionsStale();
        }
        prevMaslowState = currentMaslowState;
    }

    blinkIPAddress();

    //Make sure we're running maslow config file
    if (!Maslow.using_default_config) {
        unsigned long now = millis();
        //if the update function is not being called enough, stop everything to prevent damage
        // Skip the watchdog check during file/firmware uploads: flash write operations stall
        // both CPU cores, so update() may not run for > UPDATE_WATCHDOG_MS through no fault
        // of the motion system.  lastCallToUpdate is still refreshed so the watchdog does not
        // trigger immediately after the upload finishes.
        if (!uploadInProgress && now - lastCallToUpdate > UPDATE_WATCHDOG_MS) {
            unsigned int elapsedTime = now - lastCallToUpdate;
            log_error("Emergency stop. Update function not being called enough. " << elapsedTime << "ms since last call");
            watchdogFired = true;
            Maslow.panic();
        }
        lastCallToUpdate = now;

        Maslow.updateEncoderPositions();  //We always update encoder positions in any state,

        for (int arm = _TL; arm < ARM_COUNT; arm++) {
            axis[arm].update();  //update motor currents and belt speeds like this for now
        }

        if (safetyOn)
            safety_control();

        //quick solution for delay without blocking
        if (calibration.holding && millis() - calibration.holdTimer > calibration.holdTime) {
            calibration.holding = false;
        } else if (calibration.holding)
            return;

        //temp test function...This is used for debugging when the test command is sent
        if (test) {
            test = false;
        }

        //------------------------ Maslow State Machine

        //-------Jog or G-code execution.
        if (sys.state() == State::Jog || sys.state() == State::Cycle || sys.state() == State::Hold) {
            // With MaslowKinematics, read belt motor positions directly from the axis system
            // Axis mapping: A=TL, B=TR, C=BL, D=BR, Z=Router
            float beltLength[ARM_COUNT];
            beltLength[_TL] = steps_to_mpos(get_axis_motor_steps(0), 0);  // TL from A axis (axis 0)
            beltLength[_TR] = steps_to_mpos(get_axis_motor_steps(1), 1);  // TR from B axis (axis 1)
            beltLength[_BL] = steps_to_mpos(get_axis_motor_steps(2), 2);  // BL from C axis (axis 2)
            beltLength[_BR] = steps_to_mpos(get_axis_motor_steps(3), 3);  // BR from D axis (axis 3)
            float zPosition = steps_to_mpos(get_axis_motor_steps(4), 4);  // Z from Z axis (axis 4)

            // Set individual belt targets using the computed positions
            for (int arm = _TL; arm < ARM_COUNT; arm++) {
                axis[arm].setTarget(beltLength[arm]);
            }

            // Update internal target tracking for getTargetX/Y/Z functions
            // For now, we'll use the Z position directly and estimate X,Y from frame center
            // A full implementation would require solving inverse kinematics from belt lengths
            targetZ = zPosition;
            // Simple approximation - this could be improved with proper inverse kinematics
            // For now, we'll assume we're near the center if we don't have better information
            if (targetX == 0 && targetY == 0) {
                using namespace Kinematics;
                MaslowKinematics* kinematics = getMaslowKinematics();
                if (kinematics) {
                    targetX = (kinematics->getTrX() + kinematics->getBlX()) / 2.0f - kinematics->getCenterX();  // Approximate center X
                    targetY = (kinematics->getTrY() + kinematics->getBlY()) / 2.0f - kinematics->getCenterY();  // Approximate center Y
                }
            }

            //We used to call Maslow.setTargets() here, but now we use the axis system directly

            //This disables the belt motors until the user has completed calibration or apply tension and they have succeeded
            if (calibration.currentState == READY_TO_CUT) {
                Maslow.recomputePID();
            }
        }
        //--------Homing routines
        else if (sys.state() == State::Homing) {
            calibration.home();
        } else {  //This is confusing to understand. This is an else if so this is only run if we are not in jog, cycle, or homing
            // Clear any motor override flags to ensure motors stop
            calibration.clearMotorOverrides();
            Maslow.stopMotors();
        }

        //If we are in any state other than idle or alarm turn the cooling fan on
        if (sys.state() != State::Idle && sys.state() != State::Alarm) {
            digitalWrite(coolingFanPin, HIGH);  //keep the cooling fan on
        }
        //If we are doing calibration turn the cooling fan on
        else if (calibration.calibrationInProgress || calibration.getCurrentState() == EXTENDING ||
                 calibration.getCurrentState() == RETRACTING || calibration.getCurrentState() == RELEASE_TENSION) {
            digitalWrite(coolingFanPin, HIGH);  //keep the cooling fan on
        } else {
            digitalWrite(coolingFanPin, LOW);  //Turn the cooling fan off
        }

        //------------------------ End of Maslow State Machine

        print_motor_currents();
    }

    prevState = sys.state();  //Store for next time
}

